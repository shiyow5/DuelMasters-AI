/**
 * 日本語の太字 `**…**` が CommonMark で閉じられない問題を、パース前の文字列置換で直す (P-8)。
 *
 * ## 何が起きるか
 *
 * CommonMark の left/right-flanking 規則では、閉じ `**` の**直前が約物** (`」` `）` `:` 等) で、
 * **直後が空白でも約物でもない文字**のとき、閉じ側として認識されない。
 * 日本語は語間に空白が無いので `**「S・トリガー」**です` のような形で頻発し、
 * `**` が記号のまま画面に出る。後続に別の太字があると対応がずれて逆に壊れる。
 * ストリーミングとは無関係で、完了後の全文でも起きる (パーサの仕様)。
 *
 * ## 直し方
 *
 * `**` の内側の**先頭・末尾の約物を `**` の外へ出す**。
 * `**「X」**` → `「**X**」`、`**結論:**` → `**結論**:`。
 * 開き `**` は「約物の後 + 文字」、閉じ `**` は「文字の後 + 約物」になり flanking を満たす。
 * 見た目は括弧が太字にならなくなるだけ (デザイン判断で許容済み)。
 *
 * ## 触らないもの
 *
 * - コードフェンス (閉じ忘れ = ストリーミング途中も含む) とインラインコードの中身。
 * - 内側が約物だけ (`**「」**`) / `***` (太字+斜体) は対象外 (従来どおりの描画)。
 * - 文字列の `*` の位置を動かすだけで、HTML は生成しない。サニタイズは Markdown.tsx 側のまま。
 */

/** 約物・記号 1文字。`*` は除く (`***` を巻き込んで強調の構造を変えないため)。 */
const P = "(?:(?!\\*)[\\p{P}\\p{S}])";

/**
 * `**` + 先頭の約物 + 本文 (末尾は約物・空白以外) + 末尾の約物 + `**`。改行・`*` はまたがない。
 * 前後に `*` が続くもの (`***`) は拾わない。lookbehind は古い iOS Safari (<16.4) で
 * 構文エラーになりモジュールごと落ちるので使わず、直前の1文字を捕捉して戻す。
 */
const EMPHASIS = new RegExp(
  `(^|[^*])\\*\\*(${P}*)([^*\\n]*?[^*\\n\\p{P}\\p{S}\\s])(${P}*)\\*\\*(?!\\*)`,
  "gu",
);

/** コードフェンス (閉じ忘れは末尾まで) とインラインコード。split の捕捉で奇数番目に入る。 */
const CODE = /(```[\s\S]*?(?:```|$)|`[^`\n]*`)/;

export function fixCjkEmphasis(src: string): string {
  return src
    .split(CODE)
    .map((seg, i) =>
      i % 2
        ? seg
        : seg.replace(EMPHASIS, (m, pre: string, head: string, body: string, tail: string) =>
            head || tail ? `${pre}${head}**${body}**${tail}` : m,
          ),
    )
    .join("");
}
